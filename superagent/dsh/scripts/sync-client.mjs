const repository = fileURLToPath(new URL('../../../', import.meta.url))
const manifest = JSON.parse(readFileSync(new URL('./sync-client.manifest.json', import.meta.url), 'utf8'))
const { source, modules, adapted, referenceOnly, sharedDependencies } = manifest
const sourceShared = `${source.directory.replace(/\/client$/u, '')}/shared`
const outputRoot = join(repository, 'superagent/dsh/src/client/upstream')
const upstreamRoot = join(repository, 'temp/DS-Bot')
const expectedClientFiles = 126
