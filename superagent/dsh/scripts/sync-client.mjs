const usage = `Usage: node superagent/dsh/scripts/sync-client.mjs [--write | --check | --inventory | --check-names]

--inventory    Print the pinned file inventory, runtime disposition and destination.
--write        Sync into superagent/dsh/src/client/upstream using Git objects in temp/DS-Bot.
--check        Compare generated files with the pinned Git objects without writing.
--check-names  Scan product source and the client bundle for retired product names.

The product entry and API adapter are maintained in the client root. Runtime modules
may import ../api.js there. Reference files in upstream/reference are review material.
Files under upstream/shared are the transitive dependencies of the client inventory.
The output is generated. Edit the manifest or sync transformations instead.`

function git(upstream, ...args) {
  return execFileSync('git', ['--no-replace-objects', '-C', upstream, ...args], {
    encoding: 'utf8', maxBuffer: 8 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' },
  })
}

export function syncInventory() {
  const client = [
    ...modules.map(name => ({ name, disposition: 'module' })),
    ...Object.entries(adapted).map(([name, reason]) => ({ name, disposition: 'adapted', reason })),
    ...Object.entries(referenceOnly).map(([name, reason]) => ({ name, disposition: 'reference-only', reason })),
  ]
  if (client.length !== expectedClientFiles || new Set(client.map(entry => entry.name)).size !== expectedClientFiles) {
    throw new Error(`Expected ${expectedClientFiles} unique upstream client entries in the manifest.`)
  }
  const shared = sharedDependencies.map(name => ({ name, disposition: 'dependency' }))
  const files = [...client, ...shared].map(({ name, disposition, reason }) => {
    if (!/^(?:locales\/)?[a-z0-9]+(?:-[a-z0-9]+)*\.js$/u.test(name)) throw new Error(`Invalid manifest path: ${name}`)
    const directory = disposition === 'dependency' ? sourceShared : source.directory
    const destination = disposition === 'reference-only' ? `reference/${name}.txt`
      : disposition === 'dependency' ? `shared/${name}` : name
    return { source: `${directory}/${name}`, destination, disposition, ...(reason ? { reason } : {}) }
  }).sort((left, right) => left.source < right.source ? -1 : left.source > right.source ? 1 : 0)
  if (new Set(files.map(file => file.destination)).size !== files.length) throw new Error('Duplicate sync destinations.')
  return { source, destination: 'superagent/dsh/src/client/upstream', files }
}

function rename(text) {
  return text
    .replaceAll('https://github.com/Fei2411/DS-Bot', 'https://github.com/IceFireIcer/DS-SuperAgent')
    .replaceAll('wss://relay.dsbot.app/v1/link', 'wss://')
    .replace(/\bDS_BOT/gu, 'DS_SUPERAGENT')
    .replace(/\bdshDesktop\b/gu, 'dsSuperagentDesktop')
    .replace(/\bdsBotApp\b/gu, 'dsSuperagentApp')
    .replace(/\bdshBot(Queue)?\b/gu, 'dshSuperagent$1')
    .replace(/\bdsh-bot(?=[:.-]|\b)/gu, 'dsh-superagent')
    .replace(/\bds-bot\.browser\.(v\d+)/gu, 'ds-superagent:browser:$1')
    .replace(/\bds-bot\b/gu, 'ds-superagent')
    .replace(/\bDS Bot\b/gu, 'DS SuperAgent')
}

function extract(text, expression, entry) {
  const match = expression.exec(text)
  if (!match) throw new Error(`Could not apply ${entry.reason}: ${entry.source}`)
  return match[0].trimEnd() + '\n'
}

function transform(text, entry) {
  if (entry.disposition === 'adapted') {
    switch (entry.reason) {
      case 'namespaced-keys-only':
        text = extract(text, /^export const STORAGE = \{\n[\s\S]*?^\}/mu, entry)
        break
      case 'shared-settings-controls':
        text = `import { createElement as h, useEffect, useRef, useState } from 'react'\n\n${extract(text, /^export function InlineText\([\s\S]*?(?=\nfunction modelHint\()/mu, entry)}`
        break
      case 'omit-unlicensed-marks':
        text = 'export const AGENT_LOGOS = {}\n'
        break
      default:
        throw new Error(`Unknown transform: ${entry.reason}`)
    }
  }
  text = rename(text)
  if (entry.disposition === 'module' || entry.disposition === 'adapted') {
    text = text.replace(importPath, (statement, prefix, quote, specifier) => {
      if (specifier === './api.js') return `${prefix}${quote}../api.js${quote}`
      if (specifier.startsWith('../shared/')) return `${prefix}${quote}./shared/${specifier.slice('../shared/'.length)}${quote}`
      return statement
    })
  }
  if (retiredNames.test(text)) throw new Error(`Unmapped product identity in ${entry.source}.`)
  if (entry.disposition !== 'reference-only' && retiredTransport.test(text)) {
    throw new Error(`Retired transport in executable source: ${entry.source}.`)
  }
  return `// Derived from DS Bot ${source.version} (${source.license}), ${source.commit}:${entry.source}. Generated by sync-client.mjs.\n${text}`
}

function render(upstream) {
  const { files } = syncInventory()
  const tree = git(upstream, 'ls-tree', '-r', '-z', source.commit, '--', source.directory, sourceShared)
  const blobs = new Map(tree.split('\0').filter(Boolean).map(row => {
    const [metadata, path] = row.split('\t')
    return [path, /^100644 blob ([0-9a-f]{40})$/u.exec(metadata)?.[1]]
  }))
  const unexpected = [...blobs.keys()].filter(path => path.startsWith(`${source.directory}/`) && !files.some(file => file.source === path))
  const missing = files.filter(file => !blobs.get(file.source)).map(file => file.source)
  if (unexpected.length || missing.length) throw new Error(`Manifest mismatch: unexpected ${unexpected.join(', ') || 'none'}; missing or non-regular ${missing.join(', ') || 'none'}.`)

  const output = new Map(files.map(entry => [entry.destination, transform(git(upstream, 'cat-file', 'blob', blobs.get(entry.source)).replaceAll('\r\n', '\n'), entry)]))
  for (const [path, text] of output) {
    if (!path.endsWith('.js')) continue
    for (const [, , , specifier] of text.matchAll(importPath)) {
      if (specifier === '../api.js' && !path.includes('/')) continue
      const target = posix.join(posix.dirname(path), specifier)
      if (!output.has(target) || !target.endsWith('.js')) throw new Error(`Unapproved runtime import: ${path} → ${specifier}`)
    }
  }
  return output
}

function stat(path) {
  try { return lstatSync(path) }
  catch (error) {
    if (error.code !== 'ENOENT') throw error
    return undefined
  }
}

function readTree(root) {
  const parent = dirname(root)
  if (parent !== root) {
    for (let ancestor = parent; ; ancestor = dirname(ancestor)) {
      const entry = stat(ancestor)
      if (entry && !entry.isDirectory()) throw new Error(`Expected a real directory: ${ancestor}`)
      if (dirname(ancestor) === ancestor) break
    }
  }
  const files = new Map()
  function visit(directory) {
    const entry = stat(directory)
    if (!entry) return
    if (!entry.isDirectory()) throw new Error(`Expected a real directory: ${directory}`)
    for (const child of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, child.name)
      if (child.isDirectory()) visit(path)
      else if (child.isFile()) files.set(relative(root, path).replaceAll('\\', '/'), path)
      else throw new Error(`Expected a regular file: ${path}`)
    }
  }
  visit(root)
  return files
}

export function syncClient({ upstream = upstreamRoot, output = outputRoot, write = false } = {}) {
  output = resolve(output)
  const fromUpstream = relative(resolve(upstream), output)
  if (!fromUpstream || (!isAbsolute(fromUpstream) && fromUpstream !== '..' && !fromUpstream.startsWith(`..${sep}`))) {
    throw new Error('The output must be outside the upstream checkout.')
  }
  const current = readTree(output)
  const expected = render(upstream)
  const extra = [...current.keys()].filter(path => !expected.has(path))
  if (extra.length) throw new Error(`Unexpected files in ${output}: ${extra.join(', ')}`)
  const changed = []
  for (const [path, text] of expected) {
    const previous = current.has(path) ? readFileSync(current.get(path), 'utf8').replaceAll('\r\n', '\n') : null
    if (previous === text) continue
    if (write && previous !== null && provenance.exec(previous.split('\n', 1)[0])?.[1] !== provenance.exec(text.split('\n', 1)[0])?.[1]) {
      throw new Error(`Refusing to overwrite a file without sync provenance: ${path}`)
    }
    changed.push(path)
  }
  if (write) {
    for (const path of changed) {
      const destination = join(output, path)
      mkdirSync(dirname(destination), { recursive: true })
      writeFileSync(destination, expected.get(path))
    }
  } else if (changed.length) {
    throw new Error(`Generated files are missing or stale (${changed.length}): ${changed.join(', ')}`)
  }
  return { total: expected.size, changed: changed.length }
}

export function retiredNameLines(text) {
  return text.split(/\r?\n/u).flatMap((line, index) =>
    retiredNames.test(line) && !(index === 0 && (provenance.test(line) || overlayProvenance.test(line))) ? [index + 1] : [])
}

function checkNames() {
  const paths = ['superagent/dsh/client.js']
  for (const root of ['superagent/dsh/src', 'superagent/src', 'app/src']) {
    for (const path of readTree(join(repository, root)).keys()) paths.push(`${root}/${path}`)
  }
  const findings = paths.flatMap(path => {
    const text = readFileSync(join(repository, path), 'utf8')
    const lines = text.split(/\r?\n/u)
    const legacy = legacyContracts[path] ?? []
    return retiredNameLines(text).filter(line => !legacy.includes(lines[line - 1].trim())).map(line => `${path}:${line}`)
  })
  if (findings.length) throw new Error(`Retired product identity:\n${findings.join('\n')}`)
}

function main(args) {
  if (args.length === 0 || (args.length === 1 && args[0] === '--help')) { console.log(usage); return }
  if (args.length !== 1) throw new Error(usage)
  if (args[0] === '--inventory') { console.log(JSON.stringify(syncInventory(), null, 2)); return }
  if (args[0] === '--check-names') { checkNames(); console.log('Product naming verified.'); return }
  if (!['--check', '--write'].includes(args[0])) throw new Error(usage)
  const result = syncClient({ write: args[0] === '--write' })
  console.log(`${result.total} generated files, ${result.changed} updated.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { main(process.argv.slice(2)) }
  catch (error) { console.error(error.message); process.exitCode = 1 }
}
