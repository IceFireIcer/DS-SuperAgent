const retiredTransport = /\bapi\/bot\b/u
const importPath = /^(\s*(?:(?:import|export)\b[^'";\n]*(?:\bfrom\s*)?))(['"])([.][^'"\n]*)\2/gmu
const provenance = /^\/\/ Derived from DS Bot \d+\.\d+\.\d+ \(Apache-2\.0\), [a-f0-9]{40}:(ds-bot\/src\/(?:client|shared)\/[a-z0-9./-]+\.js)\. Generated by sync-client\.mjs\.$/u
