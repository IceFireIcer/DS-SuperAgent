import { strict as assert } from 'node:assert'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { test } from 'node:test'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'
import { retiredNameLines, syncClient, syncInventory } from '../scripts/sync-client.mjs'

const repository = fileURLToPath(new URL('../../../', import.meta.url))
const upstream = join(repository, 'temp/DS-Bot')
const { source, files } = syncInventory()
const hasPin = spawnSync('git', ['-C', upstream, 'cat-file', '-e', `${source.commit}^{commit}`], { stdio: 'ignore' }).status === 0

test('inventory names all 126 client files and keeps the legacy entry point and transport reference-only', () => {
  assert.equal(files.filter(entry => entry.source.startsWith(`${source.directory}/`)).length, 126)
  for (const name of ['api.js', 'index.js', 'settings.js', 'group-settings.js', 'local-agents-page.js']) {
    const entry = files.find(entry => entry.source === `${source.directory}/${name}`)
    assert.equal(entry.destination, `reference/${name}.txt`)
  }
  assert.equal(files.find(entry => entry.destination === 'storage.js').reason, 'namespaced-keys-only')
})

test('the naming gate only exempts the first-line provenance marker', () => {
  const header = `// Derived from DS Bot ${source.version} (${source.license}), ${source.commit}:${source.directory}/index.js. Generated by sync-client.mjs.`
  assert.deepEqual(retiredNameLines(header), [])
  assert.deepEqual(retiredNameLines(`${header}\n// DS Bot\nconst bridge = window.dshDesktop\n${header}`), [2, 3, 4])
  assert.deepEqual(retiredNameLines('// Adapted from DS Bot v0.3.8 (Apache-2.0), ds-bot/src/client/{palette,header}.js.'), [])
  assert.deepEqual(retiredNameLines('// Derived from DS Bot, ignore me\nconst key = "ds-bot:prefs"'), [1, 2])
  assert.deepEqual(retiredNameLines('const key = "ds-superagent:prefs"\nconst bridge = window.dsSuperagentDesktop\nTLS needs both key and certificate'), [])
})

test('the sync rejects output within the upstream checkout before reading or writing', () => {
  assert.throws(() => syncClient({ upstream, output: join(upstream, 'out'), write: true }), /outside the upstream checkout/u)
})

test('pinned source sync is reproducible and the executable inventory bundles through the product adapter', {
  skip: hasPin ? false : 'Pinned upstream Git objects are available from temp/DS-Bot.',
}, async () => {
  const sandbox = mkdtempSync(join(realpathSync(tmpdir()), 'superagent-sync-test-'))
  const output = join(sandbox, 'upstream')
  const read = name => readFileSync(join(output, name), 'utf8')
  try {
    writeFileSync(join(sandbox, 'package.json'), '{"type":"module"}\n')
    assert.deepEqual(syncClient({ output, write: true }), { total: 131, changed: 131 })
    assert.deepEqual(syncClient({ output }), { total: 131, changed: 0 })
    for (const entry of files) {
      const contents = read(entry.destination)
      assert(contents.split('\n', 1)[0].includes(`${source.commit}:${entry.source}.`))
      assert.deepEqual(retiredNameLines(contents), [], entry.destination)
    }

    const { STORAGE } = await import(pathToFileURL(join(output, 'storage.js')).href)
    assert(Object.values(STORAGE).every(key => key.startsWith('ds-superagent:')))
    assert.doesNotMatch(read('storage.js'), /localStorage|removeItem|migrateStorage/u)
    assert.match(read('styles.js'), /dataset\.dshSuperagent/u)
    assert.match(read('styles.js'), /--bt-/u)
    assert.match(read('i18n.js'), /NAMESPACE = 'ds-superagent'/u)
    assert.match(read('i18n.js'), /DS_SUPERAGENT_SECRETS_PASSPHRASE_FILE/u)

    const adapter = join(dirname(output), 'api.js')
    writeFileSync(adapter, "export function call() { throw new Error('Test product adapter') }\n")
    const runtime = files.filter(entry => entry.disposition !== 'reference-only')
    const result = await build({
      absWorkingDir: output,
      stdin: { contents: runtime.map(entry => `import './${entry.destination}'`).join('\n'), resolveDir: output },
      bundle: true,
      external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives', 'qrcode-generator', 'deep-view/*'],
      format: 'cjs', platform: 'browser', write: false, metafile: true, treeShaking: false,
    })
    assert(Object.keys(result.metafile.inputs).includes('../api.js'))
    assert.equal(Object.keys(result.metafile.inputs).some(path => path.startsWith('reference/')), false)
    assert.doesNotMatch(result.outputFiles[0].text, /\bapi\/bot\b|migrateStorage|legacyKeys/u)
    assert.deepEqual(retiredNameLines(result.outputFiles[0].text), [])

    writeFileSync(join(output, 'storage.js'), 'handwritten file\n')
    assert.throws(() => syncClient({ output, write: true }), /without sync provenance: storage\.js/u)
    assert.equal(read('storage.js'), 'handwritten file\n')
  } finally {
    const resolved = realpathSync(sandbox)
    assert.equal(dirname(resolved), realpathSync(tmpdir()))
    rmSync(resolved, { recursive: true, force: true })
  }
})
